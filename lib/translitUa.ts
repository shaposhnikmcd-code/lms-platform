/// Транслітерація українського тексту латиницею за постановою Кабінету Міністрів
/// України №55 від 27.01.2010 «Про впорядкування транслітерації українського
/// алфавіту латиницею» — та сама офіційна таблиця, за якою МЗС друкує прізвища
/// та імена у закордонних паспортах.
///
/// Використовується для авто-заповнення поля «Name and surname (EN)» у діалогах
/// видачі сертифікатів: менеджер одразу бачить паспортний варіант написання і
/// звіряє його з документами студента (транслітерація — підказка, а не істина:
/// у паспорті може стояти інше написання за письмовою заявою власника).
///
/// Особливості таблиці, які легко проґавити:
///   - є/ї/й/ю/я мають ДВА варіанти: на початку слова (Ye/Yi/Y/Yu/Ya) і всередині
///     (ie/i/i/iu/ia). Євген → Yevhen, але Гаєвич → Haievych.
///   - буквосполучення «зг» → `zgh` (Згурський → Zghurskyi), щоб відрізнити його
///     від «ж» → `zh`.
///   - «ь» і апостроф не передаються взагалі (Донецьк → Donetsk, Знам'янка →
///     Znamianka). Апостроф при цьому НЕ розриває слово: літера після нього
///     вважається внутрішньою (Мар'їне → Marine).
///   - «г» → `h`, «ґ» → `g` (Гонта → Honta, Ґонта → Gonta).

/// Односимвольні відповідники (позиційно-незалежні). Ключі — у нижньому регістрі:
/// вхід нормалізується до lowercase, а регістр відновлюється в кінці Word-capitalization.
const BASE: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'h',
  ґ: 'g',
  д: 'd',
  е: 'e',
  ж: 'zh',
  з: 'z',
  и: 'y',
  і: 'i',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'kh',
  ц: 'ts',
  ч: 'ch',
  ш: 'sh',
  щ: 'shch',
  ь: '',
};

/// Літери, яких немає в українському алфавіті, але які реально трапляються у
/// БД (російськомовні паспортні написання: «Алёна», «Эдуард», «Крым»). Постанова
/// №55 їх не описує — беремо звичні відповідники, щоб не лишати кирилицю в
/// латинському полі. `ъ`, як і `ь`, не передається.
const NON_UA_CYRILLIC: Record<string, string> = {
  ё: 'e',
  ы: 'y',
  э: 'e',
  ъ: '',
};

/// Уся кирилиця за Unicode-скриптом (включно з Extended-A/B/C блоками).
/// Усе кириличне, що не покрито таблицями вище, викидаємо — краще коротше ім'я,
/// ніж «Alёna» з нелатинським символом у полі, яке піде на друк англійською.
const CYRILLIC_RE = /\p{Script=Cyrillic}/u;
function isCyrillic(ch: string): boolean {
  return CYRILLIC_RE.test(ch);
}

/// Позиційні літери: `start` — на початку слова, `inner` — у будь-якій іншій позиції.
const POSITIONAL: Record<string, { start: string; inner: string }> = {
  є: { start: 'ye', inner: 'ie' },
  ї: { start: 'yi', inner: 'i' },
  й: { start: 'y', inner: 'i' },
  ю: { start: 'yu', inner: 'iu' },
  я: { start: 'ya', inner: 'ia' },
};

/// Усі варіанти апострофа, які реально трапляються у введеному вручну тексті
/// (пряма лапка, типографська, модифікатор, гравіс, акут).
const APOSTROPHES = new Set(["'", '’', 'ʼ', '`', '´', '‘']);

const LETTER_RE = /\p{L}/u;

/// Чи стоїть символ на позиції `i` на початку слова. Апострофи прозорі —
/// скануємо крізь них назад, бо «Мар'їне» це одне слово, а не два.
function isWordStart(src: string, i: number): boolean {
  for (let j = i - 1; j >= 0; j--) {
    const prev = src[j];
    if (APOSTROPHES.has(prev)) continue;
    return !LETTER_RE.test(prev);
  }
  return true;
}

/// Word-capitalization: перша літера кожного слова — велика, решта — маленькі.
/// Роздільники — пробіли та дефіси (апострофів у латинському результаті вже немає).
function capitalizeWords(value: string): string {
  return value.replace(/(^|[\s\-–—])(\p{L})/gu, (_m, sep: string, ch: string) => sep + ch.toUpperCase());
}

/// Транслітерує український рядок латиницею за КМУ №55.
/// Чиста функція: не залежить від локалі/часу, той самий вхід завжди дає той самий вихід.
/// Не-кириличні символи (латиниця, цифри, розділові знаки) проходять наскрізь.
export function translitUa(input: string): string {
  const src = (input ?? '').toLowerCase();
  let out = '';

  for (let i = 0; i < src.length; i++) {
    const ch = src[i];

    /// Апостроф не передається і не розриває слово.
    if (APOSTROPHES.has(ch)) continue;

    /// «зг» → zgh (окремий випадок таблиці, має пріоритет над посимвольним «з»).
    if (ch === 'з' && src[i + 1] === 'г') {
      out += 'zgh';
      i++;
      continue;
    }

    const positional = POSITIONAL[ch];
    if (positional) {
      out += isWordStart(src, i) ? positional.start : positional.inner;
      continue;
    }

    const base = BASE[ch] ?? NON_UA_CYRILLIC[ch];
    if (base !== undefined) {
      out += base;
      continue;
    }

    /// Невідома кирилиця (сербська/білоруська/архаїчна) — дропаємо.
    /// Латиниця, цифри, пробіли й розділові знаки проходять наскрізь.
    if (isCyrillic(ch)) continue;
    out += ch;
  }

  return capitalizeWords(out);
}

export default translitUa;

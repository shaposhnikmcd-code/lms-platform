/// Один рубильник — «Реєстрація відкрита» — і одне питання, на яке він відповідає:
/// чи народжується зараз НОВИЙ учасник Річної програми.
///
/// Навіщо окремий модуль на три рядки логіки: цю відповідь дають ДВА місця — сторінка
/// (`resolveRenewState` вирішує, показати кнопку чи текст) і `/api/wayforpay` (вирішує,
/// брати гроші чи віддати 409). Поки правило жило лише в роуті, воно розходилось із
/// панеллю, і студент бачив кнопку, яка вела у відмову платіжки. Тепер обидві сторони
/// звіряються з тим самим предикатом, а тест
/// `lib/yearlyProgramSalesConsistency.test.ts` тримає імплікацію «payable ⇒ роут 200».
///
/// Рішення власника 09.09.2026: закрита реєстрація вимикає НОВІ продажі. Доплата модуля
/// чинним студентом свого живого набору продажем не є — інакше менеджер, закривши
/// реєстрацію одразу після запуску, лишав би кожного помісячного студента без легального
/// способу заплатити за наступний модуль на весь навчальний рік.

export interface NewSaleGateInput {
  /// Прапорець з адмінки (`YearlyProgramSetting.registrationOpen`).
  registrationOpen: boolean;
  /// Invite менеджера: підписані ним умови сильніші за загальний рубильник.
  hasInvite: boolean;
  /// ADMIN або MANAGER (роль з серверної сесії, як і символічна ціна 1 ₴): їм треба
  /// проганяти НОВИЙ продаж наскрізь на pre, зокрема й тоді, коли продажі закриті.
  isStaff: boolean;
  /// У підписки, яку реюзає ця покупка, є хоч один зарахований платіж. Ознака «чинний
  /// студент» — не статус, а гроші: абандонована PENDING-спроба без оплат є тим самим
  /// новим продажем, тільки з учорашньої вкладки.
  hasPaidHistory: boolean;
}

/// true — покупку треба відхилити як новий продаж при закритій реєстрації.
export function isBlockedByClosedRegistration(input: NewSaleGateInput): boolean {
  if (input.registrationOpen || input.hasInvite || input.isStaff) return false;
  return !input.hasPaidHistory;
}

/// Персоналізація CTA-кнопки в листах-нагадуваннях Річної програми.
///
/// Винесено з `reminderTemplates.ts` навмисно: там модуль тягне Prisma, а це — чиста
/// строкова логіка, на якій тримається робоча кнопка «Оплатити наступний модуль» у
/// кожному листі. Окремий файл дає їй звичайний юніт-тест без бази.

/// Загальний лендінг Річної — дефолт для `{payUrl}`, коли персонального посилання нема.
export const PROGRAM_URL = 'https://www.uimp.com.ua/yearly-program';

/// Точний вигляд CTA-посилання у шаблонах, збережених ДО появи `{payUrl}`.
const LEGACY_CTA_HREF = `href="${PROGRAM_URL}"`;

/// Підставляє персональне посилання в шаблони, збережені менеджером ДО появи `{payUrl}`.
///
/// Дефолти в коді містять плейсхолдер, а DB-override (`EmailTemplate` `reminder.<key>`) —
/// це HTML, збережений раніше, з посиланням на лендінг ЛІТЕРАЛОМ. Без цієї заміни
/// персональне посилання отримували б лише ті, чиї шаблони менеджер не редагував — тобто
/// рівно ті, кому воно найменше потрібне. Пересохранювати всі шаблони руками теж не
/// варіант: одна забута сторінка = лист без кнопки поновлення.
///
/// Два запобіжники, обидва вистраждані:
///
/// 1. Дивимось на ШАБЛОН, а не на вже відрендерений HTML. Персональне посилання саме
///    починається з `PROGRAM_URL` (це той самий сайт), тож заміна по готовому тексту
///    після підстановки `{payUrl}` різала вже підставлений URL ще раз і давала
///    `…/renew/TOKEN/renew/TOKEN` — тобто ламала кнопку саме в тих листах, які працювали.
///    Шаблон із `{payUrl}` персоналізований за побудовою — його не чіпаємо взагалі.
/// 2. Замінюємо тільки точний `href="<лендінг>"`, а не будь-яку згадку адреси. Менеджер
///    міг написати посилання на програму в тексті листа («деталі на сторінці програми») —
///    підміняти його персональним токеном не можна.
export function withPersonalPayUrl(
  html: string,
  template: string,
  payUrl: string | null | undefined,
): string {
  if (!payUrl || payUrl === PROGRAM_URL) return html;
  if (template.includes('{payUrl}')) return html;
  return html.split(LEGACY_CTA_HREF).join(`href="${payUrl}"`);
}

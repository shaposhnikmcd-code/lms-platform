import type { RenewBlockReason } from './yearlyProgramRenewState';

/// Тексти панелі поновлення («Оплата наступного модуля») — окремо від React-компонента.
///
/// Навіщо окремий модуль: панель НЕ має права рендерити порожнечу. Людина приходить сюди
/// за посиланням з листа про гроші; порожній екран вона читає як поламаний сайт і пише
/// менеджеру. Тип `Record<RenewBlockReason, …>` робить це вимогою компілятора: додав
/// новий стан у `RenewState` — TypeScript не збереться, поки не написав до нього текст.
/// Раніше це трималось на уважності, і стан `invalid` справді рендерився нічим.
///
/// Кожен запис — три частини: заголовок (що сталось), пояснення (чому і що це значить)
/// і префікс рядка з контактом менеджера, який дописує саме посилання.

export interface RenewCopy {
  title: string;
  body: string;
  /// Речення ПЕРЕД посиланням «напишіть менеджеру» — рядок закінчується ним.
  support: string;
}

/// Мертве посилання: зіпсований/прострочений токен (редирект `?renew=expired`) або живий
/// підпис на підписці, яка вже не та. Для людини це одне й те саме, тож і текст один.
export const RENEW_DEAD_LINK_COPY: RenewCopy = {
  title: 'Посилання недійсне або застаріло',
  body: 'Оплатити наступний модуль можна нижче — у картці «Щомісячна оплата» оберіть «РАЗОВА» '
    + 'і вкажіть той самий email, з яким ви оформлювали програму.',
  support: 'Щоб отримати нове робоче посилання —',
};

/// Тексти блокувань дзеркалять 409-і з `/api/wayforpay`: сенс той самий, слова людські.
/// Сторінка не має права бути оптимістичнішою за платіжку.
const BLOCK_COPY: Record<RenewBlockReason, (missedModules: number) => RenewCopy> = {
  autopay: () => ({
    title: 'У вас підключене автосписання',
    body: 'Наступний модуль спишеться з картки автоматично в перший день модуля — оплачувати вручну не треба. '
      + 'Якщо списання не пройшло і ви хочете закрити модуль самостійно, спочатку треба вимкнути автосписання.',
    support: 'Щоб перейти на ручну оплату —',
  }),
  yearly_active: () => ({
    title: 'У вас діє Річна підписка',
    body: 'Програму оплачено одним платежем на весь рік — окремі модулі докуповувати не потрібно.',
    support: 'Якщо це помилка —',
  }),
  fully_paid: () => ({
    title: 'Усі ваші модулі вже оплачені',
    body: 'Програму сплачено повністю — доступ відкритий до кінця набору. Платити більше нема за що.',
    support: 'Якщо бачите це помилково —',
  }),
  debt: (missed) => {
    const word = missed % 10 === 1 && missed % 100 !== 11
      ? 'модуль'
      : ([2, 3, 4].includes(missed % 10) && ![12, 13, 14].includes(missed % 100) ? 'модулі' : 'модулів');
    return {
      title: 'Є пропущені модулі',
      body: `За графіком набору пропущено ${missed} ${word}. Оплата через сайт закрила б лише найближчий модуль `
        + 'і не вирівняла б графік, тому пропущене менеджер закриває вручну.',
      support: 'Щоб домовитись про оплату —',
    };
  },
  no_schedule: () => ({
    title: 'Графік модулів потребує уточнення',
    body: 'Ваша підписка не лягає на сітку модулів цього набору — оплату модуля через сайт зараз оформити не можна.',
    support: 'Щоб узгодити оплату —',
  }),
  cohort_finished: () => ({
    title: 'Ваш набір уже завершився',
    body: 'Навчальний період набору, у якому ви брали участь, добіг кінця — оплатити ще один модуль у ньому вже не можна.',
    support: 'Щодо доступу до матеріалів і наступного набору —',
  }),
  archived: () => ({
    title: 'Підписку деактивовано',
    body: 'Ця підписка більше не активна, тому оплату модуля через сайт оформити не вийде.',
    support: 'Щоб відновити навчання —',
  }),
  registration_closed: () => ({
    title: 'Оплата через сайт тимчасово закрита',
    body: 'Прийом оплат на сторінці програми зараз призупинено. Ваш доступ це не змінює — модуль можна закрити через менеджера.',
    support: 'Щоб оплатити модуль —',
  }),
};

export function renewBlockCopy(reason: RenewBlockReason, missedModules = 0): RenewCopy {
  return BLOCK_COPY[reason](missedModules);
}

/// Усі стани блокування — для тестів і для перебору. Ключі `Record` вище повні за типом.
export const RENEW_BLOCK_REASONS = Object.keys(BLOCK_COPY) as RenewBlockReason[];
